//! Rust DSL from the screen schema: a function per built-in node and library element and a [`Node`]
//! method per property — chained, as in the hand-written `uison_ui::dsl`:
//!
//! ```ignore
//! column().gap(12).children([text("Hello").size(20), button("+1").on_click(|cx| …)])
//! ```
//!
//! Methods with their own signature (`bold()`, `child`, `children`, `bind`, `options`, events) are written
//! by hand in `dsl.rs`; here — only "name = value". Custom components (`components.json`) get
//! functions and a trait with their own properties ([`components`]).

use uison_ui::schema;

use crate::{INTERNAL, POSITIONAL, Widget, components as widgets_of, standard as std_widgets};

/// Constructors with their own signature live in `dsl.rs`: `center(child)`, `scroll(child)`, `card(children)`,
/// `section(title, children)`, `for_each`, `list`; `Box` is `container()` (`box` is a keyword).
const HAND_FNS: [&str; 7] = ["Box", "For", "List", "Center", "Scroll", "Card", "Section"];

/// Properties whose method is hand-written: flags without an argument (`bold()`), nodes (`child`, `children`),
/// option lists (`options`, `tabs`), `pos(x, y)`, events (`on`), `as`/`do` of `For` and `List`.
const HAND_METHODS: [&str; 11] = ["bold", "italic", "password", "child", "children", "options", "tabs", "pos", "on", "as", "do"];

/// Methods of `Node` itself — properties with these names would need a different name.
const NODE_METHODS: [&str; 4] = ["new", "kind", "prop", "to_json"];

const KEYWORDS: [&str; 52] = [
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box",
    "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

/// `maxLines` → `max_lines`, `IconButton` → `icon_button`; a keyword gets a trailing `_`.
pub(crate) fn snake(name: &str) -> String {
    let mut s = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                s.push('_');
            }
            s.push(c.to_ascii_lowercase());
        } else {
            s.push(c);
        }
    }
    if KEYWORDS.contains(&s.as_str()) {
        s.push('_');
    }
    s
}

/// Properties of all widgets: JSON name → which elements have it (in order of first appearance).
fn props(widgets: &[Widget]) -> Vec<(String, Vec<String>)> {
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    for w in widgets {
        for f in w.fields.iter().chain(&w.slots) {
            match out.iter_mut().find(|(p, _)| *p == f.json) {
                Some((_, ws)) => ws.push(w.name.clone()),
                None => out.push((f.json.clone(), vec![w.name.clone()])),
            }
        }
    }
    out
}

/// Where a property exists — for the comment; ones common to all — "any node".
fn where_doc(ws: &[String], total: usize) -> String {
    if ws.len() * 10 >= total * 9 {
        return "any node".into();
    }
    let mut s = ws.iter().take(8).cloned().collect::<Vec<_>>().join(", ");
    if ws.len() > 8 {
        s.push_str(&format!(" and {} more", ws.len() - 8));
    }
    s
}

fn header(what: &str) -> String {
    format!(
        "// {what}: Rust DSL — element functions and chained property methods.\n\
         // Generated by uison-gen (crates/uison-gen) — don't edit by hand.\n\n"
    )
}

/// The standard `widgets.rs` for `uison_ui::dsl`: built-in nodes and the element library.
pub fn standard() -> String {
    let widgets: Vec<Widget> = std_widgets();
    let mut out = header("uison");
    out.push_str("use super::{IntoJson, Node, node};\n\n");
    // Element functions.
    for w in widgets.iter().filter(|w| !HAND_FNS.contains(&w.name.as_str()) && !INTERNAL.contains(&w.name.as_str())) {
        function(&mut out, w);
    }
    // Property methods.
    out.push_str("impl Node {\n");
    let all = props(&widgets);
    let total = widgets.len();
    for (p, ws) in &all {
        if HAND_METHODS.contains(&p.as_str()) {
            continue;
        }
        let m = snake(p);
        assert!(!NODE_METHODS.contains(&m.as_str()), "property '{p}' clashes with a Node method");
        // Description: the common one from the schema, or from the first element that has the property.
        let doc = schema::doc("", p).map(String::from).or_else(|| {
            widgets.iter().find_map(|w| w.fields.iter().chain(&w.slots).find(|f| f.json == *p).and_then(|f| f.doc.clone()))
        });
        let doc = doc.map_or(String::new(), |d| format!("    /// {d}.\n    ///\n"));
        out.push_str(&format!(
            "{doc}    /// `{p}` — {}.\n    pub fn {m}(self, v: impl IntoJson) -> Node {{\n        self.prop(\"{p}\", v)\n    }}\n\n",
            where_doc(ws, total)
        ));
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n");
    out
}

fn function(out: &mut String, w: &Widget) {
    let f = snake(&w.name);
    match POSITIONAL.iter().find(|(n, _)| *n == w.name) {
        Some((_, main)) => {
            let arg = snake(main);
            out.push_str(&format!(
                "/// `{0}` — the main property `{1}` as the argument.\npub fn {f}({arg}: impl IntoJson) -> Node {{\n    node(\"{0}\").prop(\"{1}\", {arg})\n}}\n\n",
                w.name, main
            ));
        }
        None => out.push_str(&format!("/// `{0}`.\npub fn {f}() -> Node {{\n    node(\"{0}\")\n}}\n\n", w.name)),
    }
}

/// Custom components: a function for each and a trait `name` with methods for properties the
/// standard elements don't have (theirs are already on `Node`). In the program: `use app::*;`.
pub fn components(srcs: &[&str], name: &str, what: &str) -> Result<String, uison_json::Error> {
    let mut widgets = Vec::new();
    for s in srcs {
        widgets.extend(widgets_of(s, false)?);
    }
    let std_props: Vec<String> = props(&std_widgets()).into_iter().map(|(p, _)| p).collect();
    let mut out = header(what);
    out.push_str("#![allow(dead_code)]\n\nuse uison::ui::IntoJson;\nuse uison::ui::dsl::{Node, node};\n\n");
    for w in &widgets {
        out.push_str(&format!("/// Component `{0}`.\npub fn {1}() -> Node {{\n    node(\"{0}\")\n}}\n\n", w.name, snake(&w.name)));
    }
    let own: Vec<(String, Vec<String>)> =
        props(&widgets).into_iter().filter(|(p, _)| !std_props.contains(p) && !HAND_METHODS.contains(&p.as_str())).collect();
    if own.is_empty() {
        return Ok(out);
    }
    out.push_str(&format!("/// Properties of your own components, chained: `use …::{name};`.\npub trait {name} {{\n"));
    for (p, ws) in &own {
        out.push_str(&format!("    /// `{p}` — {}.\n    fn {}(self, v: impl IntoJson) -> Node;\n", ws.join(", "), snake(p)));
    }
    out.push_str("}\n\n");
    out.push_str(&format!("impl {name} for Node {{\n"));
    for (p, _) in &own {
        out.push_str(&format!("    fn {}(self, v: impl IntoJson) -> Node {{\n        self.prop(\"{p}\", v)\n    }}\n", snake(p)));
    }
    out.push_str("}\n");
    Ok(out)
}
