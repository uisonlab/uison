//! Element reference (`docs/screens/elements.md`) from the same schema as the C++ widgets and the Rust DSL:
//! built-in nodes, the element library, common properties and behaviors. The Russian `docs/ru/screens/elements.md`
//! is a translation.

use uison_ui::schema;

use crate::rust::snake;
use crate::{INTERNAL, POSITIONAL, Widget, standard};

const CONTAINERS: [&str; 12] = ["Box", "Row", "Column", "Stack", "Center", "Align", "Spacer", "Wrap", "Flow", "Scroll", "List", "For"];
const GRAPHICS: [&str; 7] = ["Image", "Rect", "Circle", "Line", "Tri", "Vector", "Canvas"];

fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

fn table(out: &mut String, rows: &[(String, String)]) {
    out.push_str("| property | C++ / Rust | description |\n|---|---|---|\n");
    for (p, d) in rows {
        out.push_str(&format!("| `{p}` | `{}` | {} |\n", snake(p).trim_end_matches('_'), cell(d)));
    }
    out.push('\n');
}

/// The widget's own properties (without common ones and behaviors).
fn own(w: &Widget) -> Vec<(String, String)> {
    w.fields
        .iter()
        .chain(&w.slots)
        .filter(|f| !schema::COMMON.contains(&f.json.as_str()) && !schema::BEHAVIOR.contains(&f.json.as_str()))
        .map(|f| (f.json.clone(), f.doc.clone().unwrap_or_default()))
        .collect()
}

fn element(out: &mut String, w: &Widget) {
    out.push_str(&format!("### {}\n\n", w.name));
    if let Some((_, main)) = POSITIONAL.iter().find(|(n, _)| *n == w.name) {
        out.push_str(&format!(
            "The main property `{main}` goes first: C++ `{0}(\"…\", {{…}})`, Rust `{1}(\"…\")`.\n\n",
            w.name,
            snake(&w.name)
        ));
    }
    let rows = own(w);
    if rows.is_empty() {
        out.push_str("No properties of its own — only the common ones.\n\n");
    } else {
        table(out, &rows);
    }
    if w.name == "Icon" {
        out.push_str(&format!("Icons: {}.\n\n", icon_names().iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", ")));
    }
    if !w.events.is_empty() && w.name != "For" {
        out.push_str(&format!("Events: {}.\n\n", w.events.iter().map(|e| format!("`{e}`")).collect::<Vec<_>>().join(", ")));
    }
}

/// Icon names: the `cases` keys in the body of `Icon` (`lib/icons.json`).
fn icon_names() -> Vec<String> {
    let Some((_, src)) = schema::standard_sources().iter().find(|(f, _)| f.ends_with("icons.json")) else { return Vec::new() };
    let v = uison_json::parse(src).expect("icons.json");
    let cases = ["Icon", "body", "Vector", "children", "cases"].iter().try_fold(&v, |v, k| v.get(k));
    cases.and_then(|c| c.as_object()).map(|o| o.iter().map(|(k, _)| k.to_string()).collect()).unwrap_or_default()
}

pub fn elements() -> String {
    let widgets = standard();
    let mut out = String::from(
        "# Elements\n\n\
         **English** · [Русский](../ru/screens/elements.md)\n\n\
         Generated by `uison-gen --md` from the screen schema (`uison_ui::schema`) and the library `lib/*.json` — don't edit by hand:\n\
         `cargo run -p uison-gen -- --md -o docs/screens/elements.md`.\n\n\
         Properties are named as in JSON. In C++ (`uison_widgets.hpp`) and in the Rust DSL the names are the same in `snake_case`: `maxLines` → `max_lines`.\n\
         Any property can also be set directly: `.prop(\"maxLines\", 2)` (C++ and Rust).\n\n",
    );
    out.push_str("## Common properties\n\nAvailable on every node and component.\n\n");
    let common: Vec<(String, String)> =
        schema::COMMON.iter().map(|p| (p.to_string(), schema::doc("", p).unwrap_or("").to_string())).collect();
    table(&mut out, &common);
    out.push_str("## Behaviors\n\nOn built-in nodes (`Box`, `Row`, `Column`, `Stack`, `Wrap`…): the library elements are built from them.\n\n");
    let beh: Vec<(String, String)> =
        schema::BEHAVIOR.iter().map(|p| (p.to_string(), schema::doc("", p).unwrap_or("").to_string())).collect();
    table(&mut out, &beh);
    let group = |out: &mut String, title: &str, names: &[&str]| {
        out.push_str(&format!("## {title}\n\n"));
        for n in names {
            if let Some(w) = widgets.iter().find(|w| w.name == *n) {
                element(out, w);
            }
        }
    };
    group(&mut out, "Layout", &CONTAINERS);
    group(&mut out, "Text and input", &["Text", "Input"]);
    group(&mut out, "Graphics", &GRAPHICS);
    out.push_str("## Element library\n\nThe `lib/*.json` components: built from the built-in nodes, just like your program's own components.\n\n");
    for w in &widgets {
        let n = w.name.as_str();
        if schema::BUILTINS.contains(&n) || INTERNAL.contains(&n) {
            continue;
        }
        element(&mut out, w);
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
