//! Flutter-style Rust DSL: builds the same node tree as a screen JSON file.
//!
//! ```ignore
//! use uison::prelude::*;
//! let screen = column().gap(16).padding(24).children([
//!     text("Sign up").size(22).bold(),
//!     text_field().label("Name").bind("form.name"),
//!     checkbox("I agree to the terms").bind("form.agree"),
//!     button("Submit").disabled("!@form.agree").on_click(|cx| cx.data.set("sent", true)),
//! ]);
//! println!("{}", screen.to_json()); // the same screen as JSON
//! ```
//!
//! Element functions and property methods (`gap`, `size`, `max_lines`…) are generated by `uison-gen --rust` from
//! the same schema `Ui` checks a screen against (`widgets.rs`); here is what has its own signature:
//! child nodes, flags, bindings, option lists and events.

use std::borrow::Cow;
use std::cell::{Cell, RefCell};

use crate::{Cx, IntoJson, Json};

#[path = "widgets.rs"]
mod widgets;
pub use widgets::*;

/// A tree node: type and properties in insertion order.
#[derive(Clone, Debug, PartialEq)]
pub struct Node {
    kind: String,
    props: Vec<(String, Json)>,
}

impl IntoJson for Node {
    fn into_json(self) -> Json {
        let props = Json::Object(self.props.into_iter().map(|(k, v)| (Cow::Owned(k), v)).collect());
        Json::Object(vec![(Cow::Owned(self.kind), props)])
    }
}

/// A binding: `"form.name"` and `"@form.name"` are the same.
fn binding(path: &str) -> String {
    if path.starts_with('@') || path.starts_with("!@") { path.to_string() } else { format!("@{path}") }
}

/// Option list `[{ value, label }]` for RadioGroup, Select, Tabs.
fn options(items: &[(&str, &str)]) -> Json {
    Json::Array(
        items
            .iter()
            .map(|(v, l)| {
                Json::Object(vec![(Cow::Borrowed("value"), v.into_json()), (Cow::Borrowed("label"), l.into_json())])
            })
            .collect(),
    )
}

type Handler = Box<dyn FnMut(&mut Cx)>;

thread_local! {
    /// Closures from `.on_click(|cx| …)`: the action name `~hN` goes into the node, the closure itself stays here until
    /// `Ui` takes it (in `Ui::from_node` and after every event).
    static HANDLERS: RefCell<Vec<(String, Handler)>> = const { RefCell::new(Vec::new()) };
    static NEXT: Cell<u64> = const { Cell::new(0) };
}

/// Closures `Ui` hasn't taken yet.
pub(crate) fn take_handlers() -> Vec<(String, Handler)> {
    HANDLERS.with(|h| std::mem::take(&mut *h.borrow_mut()))
}

impl Node {
    pub fn new(kind: &str) -> Node {
        Node { kind: kind.to_string(), props: Vec::new() }
    }

    pub fn kind(&self) -> &str {
        &self.kind
    }

    /// Any property: `.prop("maxLines", 2)`.
    pub fn prop(mut self, key: &str, v: impl IntoJson) -> Node {
        let v = v.into_json();
        match self.props.iter_mut().find(|(k, _)| k == key) {
            Some((_, slot)) => *slot = v,
            None => self.props.push((key.to_string(), v)),
        }
        self
    }

    /// The same node as complex JSON (indented).
    pub fn to_json(&self) -> String {
        self.clone().into_json().to_json_pretty()
    }

    // ------------------------------------------------------------ events

    /// Event → action by name (the handler is `Ui::on`; hotkeys and timers use the same
    /// name): `.on("click", "add")`, like `on: { click: "add" }` in JSON.
    pub fn on(mut self, event: &str, action: &str) -> Node {
        let mut on = self.props.iter().find(|(k, _)| k == "on").map_or_else(Json::object, |(_, v)| v.clone());
        on.set(event, action.into_json());
        self = self.prop("on", on);
        self
    }

    /// Event → closure: `.on_event("menu", |cx| …)`. In a `For`/`List` template one closure serves all
    /// rows — `cx.key` tells which row.
    pub fn on_event(self, event: &str, f: impl FnMut(&mut Cx) + 'static) -> Node {
        let name = NEXT.with(|n| {
            let i = n.get();
            n.set(i + 1);
            format!("~h{i}")
        });
        HANDLERS.with(|h| h.borrow_mut().push((name.clone(), Box::new(f))));
        self.on(event, &name)
    }

    /// Press: `button("+1").on_click(|cx| …)`. By action name — `.on("click", "inc")`.
    pub fn on_click(self, f: impl FnMut(&mut Cx) + 'static) -> Node {
        self.on_event("click", f)
    }

    /// The value changed (field, checkbox, slider…).
    pub fn on_change(self, f: impl FnMut(&mut Cx) + 'static) -> Node {
        self.on_event("change", f)
    }

    /// Enter in a text field.
    pub fn on_submit(self, f: impl FnMut(&mut Cx) + 'static) -> Node {
        self.on_event("submit", f)
    }

    // ------------------------------------------------------------ children

    pub fn child(self, n: Node) -> Node {
        self.prop("child", n)
    }

    pub fn children(self, items: impl IntoIterator<Item = Node>) -> Node {
        self.prop("children", items.into_iter().map(IntoJson::into_json).collect::<Vec<_>>())
    }

    // ------------------------------------------------------------ conveniences

    /// Width "all available space".
    pub fn fill_w(self) -> Node {
        self.prop("w", "fill")
    }

    pub fn fill_h(self) -> Node {
        self.prop("h", "fill")
    }

    pub fn pos(self, x: f32, y: f32) -> Node {
        self.prop("pos", [x, y])
    }

    /// Border: color and width.
    pub fn border(self, c: &str, width: f32) -> Node {
        self.prop("stroke", c).prop("width", width)
    }

    pub fn bold(self) -> Node {
        self.prop("bold", true)
    }

    pub fn italic(self) -> Node {
        self.prop("italic", true)
    }

    pub fn password(self) -> Node {
        self.prop("password", true)
    }

    /// Text alignment: left, center, right.
    pub fn text_align(self, a: &str) -> Node {
        self.prop("align", a)
    }

    /// Bind the element's value to a path in the model. The property depends on the type:
    /// Checkbox/Switch — `checked`, the rest — `value`.
    pub fn bind(self, path: &str) -> Node {
        let prop = match self.kind.as_str() {
            "Checkbox" | "Switch" => "checked",
            _ => "value",
        };
        self.prop(prop, binding(path))
    }

    /// Options for RadioGroup and Select: `[(value, label)]`.
    pub fn options(self, items: &[(&str, &str)]) -> Node {
        self.prop("options", options(items))
    }

    /// Tabs for Tabs: `[(value, label)]`.
    pub fn tabs(self, items: &[(&str, &str)]) -> Node {
        self.prop("tabs", options(items))
    }

    pub fn range(self, min: f32, max: f32, step: f32) -> Node {
        self.prop("min", min).prop("max", max).prop("step", step)
    }
}

// ------------------------------------------------------------ constructors with their own signature

pub fn node(kind: &str) -> Node {
    Node::new(kind)
}

/// `Box` container (`box` is a Rust keyword).
pub fn container() -> Node {
    node("Box")
}

pub fn center(child: Node) -> Node {
    node("Center").child(child)
}

pub fn scroll(child: Node) -> Node {
    node("Scroll").child(child)
}

pub fn progress(value: impl IntoJson) -> Node {
    node("ProgressBar").prop("value", value)
}

pub fn card(children: impl IntoIterator<Item = Node>) -> Node {
    node("Card").children(children)
}

pub fn section(title: impl IntoJson, children: impl IntoIterator<Item = Node>) -> Node {
    node("Section").prop("title", title).children(children)
}

/// Repeat `item` for each element of the array at path `each`; inside it, `@<alias>`.
pub fn for_each(each: &str, alias: &str, item: Node) -> Node {
    node("For").prop("each", binding(each)).prop("as", alias).prop("do", item)
}

/// Virtualized scrolling list: only visible items are expanded.
pub fn list(items: &str, alias: &str, item_height: f32, item: Node) -> Node {
    node("List").prop("items", binding(items)).prop("as", alias).prop("itemHeight", item_height).prop("item", item)
}

/// A value in complex-JSON language right in code — for selectors and functions:
/// `json(r#"{ switch: "@filter", cases: { done: "@t.done" }, default: true }"#)`.
pub fn json(src: &str) -> Json {
    uison_json::parse(src).unwrap_or_else(|e| panic!("dsl::json: {e}")).into_owned()
}
